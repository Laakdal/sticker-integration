// Renders the bundled starter pack artwork with sharp. Run: npm run generate:bundled
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

import { generateStarterMoves } from './bundled/starter-moves.mjs';
import { BUNDLED_PACKS_VERSION } from './bundled/version.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'bundled-packs');
const PACK_ID = 'bundled.starter-basics';
const outDir = join(root, 'starter-basics');
const STATIC_MAX = 100 * 1024;
const TRAY_MAX = 50 * 1024;

const stickers = [
  { id: 's1', word: 'HI!', color: '#FFB300', mouth: 'smile', emojis: ['👋', '😀'], a11y: 'Yellow face waving hi' },
  { id: 's2', word: 'LOL', color: '#43A047', mouth: 'laugh', emojis: ['😂'], a11y: 'Green face laughing out loud' },
  { id: 's3', word: 'OK', color: '#1E88E5', mouth: 'smile', emojis: ['👌'], a11y: 'Blue face saying OK' },
  { id: 's4', word: 'NO', color: '#E53935', mouth: 'frown', emojis: ['🙅'], a11y: 'Red face saying no' },
  { id: 's5', word: 'WOW', color: '#8E24AA', mouth: 'o', emojis: ['😮'], a11y: 'Purple face surprised saying wow' },
  { id: 's6', word: 'BYE', color: '#00897B', mouth: 'smile', emojis: ['👋', '😊'], a11y: 'Teal face saying bye' },
];

const mouths = {
  smile: '<path d="M186 282 Q256 350 326 282" stroke="#3E2723" stroke-width="18" fill="none" stroke-linecap="round"/>',
  laugh: '<path d="M176 270 Q256 380 336 270 Z" fill="#3E2723"/>',
  frown: '<path d="M186 322 Q256 262 326 322" stroke="#3E2723" stroke-width="18" fill="none" stroke-linecap="round"/>',
  o: '<ellipse cx="256" cy="302" rx="34" ry="42" fill="#3E2723"/>',
};

function svgFor({ word, color, mouth }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">
  <circle cx="256" cy="226" r="180" fill="#FFFFFF"/>
  <circle cx="256" cy="226" r="164" fill="${color}"/>
  <circle cx="200" cy="196" r="22" fill="#3E2723"/>
  <circle cx="312" cy="196" r="22" fill="#3E2723"/>
  ${mouths[mouth]}
  <text x="256" y="480" text-anchor="middle" font-family="Arial Black, Arial, sans-serif" font-weight="900"
        font-size="104" fill="${color}" stroke="#FFFFFF" stroke-width="14" paint-order="stroke">${word}</text>
</svg>`;
}

async function encodeStatic(svg) {
  for (let quality = 90; quality >= 40; quality -= 10) {
    const buf = await sharp(Buffer.from(svg)).resize(512, 512).webp({ quality, effort: 6 }).toBuffer();
    if (buf.length <= STATIC_MAX) return buf;
  }
  throw new Error('Could not fit sticker under 100 KB');
}

mkdirSync(outDir, { recursive: true });
const packStickers = [];
for (const s of stickers) {
  const buf = await encodeStatic(svgFor(s));
  writeFileSync(join(outDir, `${s.id}.webp`), buf);
  packStickers.push({
    id: s.id, file: `${s.id}.webp`, emojis: s.emojis, accessibilityText: s.a11y,
    animated: false, sizeBytes: buf.length, editable: false,
  });
}

const tray = await sharp(Buffer.from(svgFor(stickers[0]))).resize(96, 96).png({ compressionLevel: 9, palette: true }).toBuffer();
if (tray.length > TRAY_MAX) throw new Error('Tray icon over 50 KB');
writeFileSync(join(outDir, 'tray.png'), tray);

const timestamp = '2026-09-25T00:00:00.000Z';
const pack = {
  id: PACK_ID, name: 'Starter Basics', publisher: 'Sticker Maker', trayIcon: 'tray.png', animated: false,
  stickers: packStickers, imageDataVersion: BUNDLED_PACKS_VERSION, avoidCache: false, origin: 'bundled',
  createdAt: timestamp, updatedAt: timestamp,
};
writeFileSync(join(outDir, 'pack.json'), JSON.stringify(pack, null, 2));

const moves = await generateStarterMoves(root, timestamp);
const manifestPacks = [
  { dir: 'starter-basics', files: ['tray.png', ...packStickers.map((s) => s.file)] },
  moves,
];
const entries = manifestPacks
  .map(({ dir, files }) => {
    const fileLines = files.map((f) => `      '${f}': require('./${dir}/${f}'),`).join('\n');
    return `  {\n    pack: require('./${dir}/pack.json'),\n    files: {\n${fileLines}\n    },\n  },`;
  })
  .join('\n');
writeFileSync(
  join(root, 'index.ts'),
  `// Generated by scripts/generate-bundled-packs.mjs — do not edit by hand.
import type { BundledPackSource } from '@/services/bundledPacks';

/** Bump when bundled pack contents change so existing installs re-copy them. */
export const BUNDLED_PACKS_VERSION = ${BUNDLED_PACKS_VERSION};

export const bundledPacks: BundledPackSource[] = [
${entries}
];
`,
);
console.log(`Generated ${packStickers.length} static stickers in ${outDir} and ${moves.files.length - 1} animated stickers in ${join(root, moves.dir)}`);
